/// أي Repository ممكن يصير عندو تعديلات وقت ما التطبيق كان أوفلاين
/// (مثلاً: تعديل بروفايل، إنشاء/حذف Workspace أو Task...)
/// لازم يطبّق هاد الـ interface حتى الـ SyncManager يقدر يزامنه تلقائياً
/// لحظة ما يرجع الاتصال بالإنترنت.
abstract class Syncable {
  /// يرسل كل العمليات المعلّقة (Pending) للسيرفر بالترتيب،
  /// ويفرّغ الطابور المحلي بعد ما تنجح كل عملية.
  /// لازم ما ترمي exception — أي فشل لازم يتلقّط جوا التنفيذ نفسه
  /// حتى ما توقف مزامنة باقي الـ Repositories.
  Future<void> syncPendingChanges();
}
